"""
Node model.

Defines the Node table — a single story beat within a book. Each node
has a title, description, type (entry/beat/exit/ending), a position on
the canvas (x, y), and optional story text generated by AI.

Nodes contain choices that point to other nodes within the same book.
Items and encounters are stored as JSON arrays of IDs for simplicity
during the authoring phase. A proper many-to-many junction table could
be added later if needed.

Relationships:
  - Node.book: Many-to-one to Book.
  - Node.act: Many-to-one to Act.
  - Node.choices: One-to-many to Choice (where choice.source_node_id = node.id).
  - Node.previous_node: Optional reference to the prior beat for story continuity.
"""

from typing import List, Optional

from sqlalchemy import String, Float, ForeignKey
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class Node(Base):
    __tablename__ = "node"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    book_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("book.id"), nullable=False
    )
    act_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("act.id"), nullable=True
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    locationId: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    items: Mapped[str] = mapped_column(String, default="[]")
    encounters: Mapped[str] = mapped_column(String, default="[]")
    type: Mapped[str] = mapped_column(String(20), default="beat")
    choices: Mapped[str] = mapped_column(String, default="[]")
    x: Mapped[float] = mapped_column(Float, default=0.0)
    y: Mapped[float] = mapped_column(Float, default=0.0)

    # AI story generation fields (populated in Phase 7+)
    storyText: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    storyStatus: Mapped[str] = mapped_column(String, default="pending")
    storyModel: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    storyPrompt: Mapped[Optional[str]] = mapped_column(String, nullable=True)

    # Relationships
    book: Mapped["app.models.book.Book"] = relationship(
        "Book", back_populates="nodes"
    )
    act: Mapped[Optional["app.models.act.Act"]] = relationship("Act")
    choices_list: Mapped[List["app.models.choice.Choice"]] = relationship(
        "Choice", back_populates="source_node", foreign_keys="Choice.source_node_id",
        cascade="all, delete-orphan"
    )
