"""Identifier generation.

Primary keys are UUIDv7 (RFC 9562): a 48-bit millisecond timestamp followed by
random bits, so ids sort by creation time and index well. Within a single
millisecond the 12-bit ``rand_a`` field is used as a counter (RFC 9562 §6.2,
method 1) so ids generated by this process are strictly increasing.
"""

import os
import threading
import time
import uuid

_lock = threading.Lock()
_last_ms = 0
_counter = 0
_COUNTER_MAX = 0xFFF


def uuid7() -> uuid.UUID:
    """Return a new, monotonically increasing UUIDv7."""
    global _last_ms, _counter
    with _lock:
        ms = time.time_ns() // 1_000_000
        if ms > _last_ms:
            _last_ms = ms
            _counter = int.from_bytes(os.urandom(2)) & 0x7FF  # leave headroom
        else:
            # Same millisecond (or clock went backwards): keep ordering.
            _counter += 1
            if _counter > _COUNTER_MAX:
                _last_ms += 1
                _counter = 0
            ms = _last_ms
        counter = _counter

    rand_b = int.from_bytes(os.urandom(8)) & ((1 << 62) - 1)
    value = (ms & ((1 << 48) - 1)) << 80
    value |= 0x7 << 76  # version
    value |= counter << 64
    value |= 0b10 << 62  # RFC 4122 variant
    value |= rand_b
    return uuid.UUID(int=value)


def new_id() -> str:
    """Return a new UUIDv7 as its canonical 36-character string."""
    return str(uuid7())
